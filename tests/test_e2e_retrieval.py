def _evaluation_response(submission_id, rubric_id, validator_id, score=82):
    return {
        "schemaVersion": "0.1.0",
        "submissionId": submission_id,
        "rubricId": rubric_id,
        "validatorId": validator_id,
        "evaluationType": "research_paper",
        "criterionScores": [
            {
                "criterionId": f"criterion-{i}",
                "score": score // 4,
                "confidence": 8500,
                "rationale": "Verified criterion rationale.",
            }
            for i in range(1, 5)
        ],
        "overallRecommendation": "accepted",
        "overallConfidence": 8500,
        "summary": "E2E retrieval test: verified content.",
        "limitations": ["Test-only evaluation."],
        "fairnessChecklist": {"irrelevantStatusSignalsExcluded": True},
        "modelMetadata": {"promptVersion": "ace-e2e-test-v1"},
    }


def test_e2e_evaluator_receives_complete_artifact_and_rubric_with_five_validators(
    direct_vm, direct_deploy, direct_alice
):
    """
    Full E2E: verified artifact + rubric flow through evaluate_submission.

    Verifies:
    - artifact and rubric are retrieved through gl.nondet.web.get()
    - hash verification passes (fail-closed guards remain active)
    - exactly five evaluator prompts contain the complete artifact text
    - exactly five evaluator prompts contain the complete rubric text
    - consensus proceeds and the submission is finalized
    """
    contract, submission_id, rubric_id, profile_id = _build_e2e_submission(
        direct_vm, direct_deploy, direct_alice
    )
    contract.freeze_submission(submission_id)

    # Each evaluator prompt must contain the complete verified artifact and rubric
    for index, score in enumerate((82, 85, 83, 84, 82), start=1):
        prompt_regex = (
            rf"(?s)ACE_EVALUATION.*Evaluator ordinal: {index}.*"
            rf"\[SECTION A: VERIFIED SUBMITTED WORK\].*"
            rf"{re.escape(ARTIFACT_TEXT[:50])}.*"
            rf"\[SECTION B: COMPLETE VERIFIED RUBRIC\].*"
            rf"{re.escape(RUBRIC_CRITERIA_TEXT[:50])}"
        )
        direct_vm.mock_llm(
            prompt_regex,
            json.dumps(
                _evaluation_response(submission_id, rubric_id, f"ace-validator-{index}", score)
            ),
        )

    report_ids = [
        f"ace-report-{i}-{submission_id}-{str(contract.owner)}"
        for i in range(1, 6)
    ]
    direct_vm.mock_llm(
        r"ACE_CONSENSUS",
        json.dumps({
            "submissionId": submission_id,
            "rubricId": rubric_id,
            "reportIds": report_ids,
            "decision": "accepted",
            "confidence": 8400,
            "summary": "E2E consensus: all five validators agree.",
            "methodId": "ace-ai-consensus-v1",
        }),
    )

    consensus_id = contract.evaluate_submission(submission_id, profile_id)

    # Verify finalization
    assert consensus_id == f"ace-consensus-{submission_id}"
    assert contract.get_submission(submission_id).status == "finalized"

    # Verify exactly five reports
    stored_report_ids = contract.list_reports(submission_id, 0, 10)
    assert len(stored_report_ids) == 5, (
        f"Expected exactly 5 evaluator reports, got {len(stored_report_ids)}"
    )

    # Verify consensus result
    result = contract.get_consensus_result(consensus_id)
    assert result.decision == "accepted"
    assert result.status == "finalized"

    # Verify validator agreement runs correctly
    assert direct_vm.run_validator(index=0)
    assert direct_vm.run_validator(index=1)


